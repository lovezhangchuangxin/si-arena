const FACE_LETTERS = ["U", "R", "F", "D", "L", "B"];
/** One 90° turn of the whole cube about the U-D axis, as a face permutation. */
const ROTATE_FACE = [0, 2, 4, 3, 5, 1];
const FACE_OF = { U: 0, R: 1, F: 2, D: 3, L: 4, B: 5 };
const RIGHT_OF = { 2: 1, 1: 5, 5: 4, 4: 2 };
const LEFT_OF = { 1: 2, 5: 1, 4: 5, 2: 4 };
const CORNER_ORDER = [4, 5, 6, 7];
const EDGE_ORDER = [8, 9, 10, 11];
const CROSS_SLOTS = [5, 4, 7, 6];
const U_ABOVE = { 4: 0, 5: 1, 6: 2, 7: 3 };
const SIDE_FACE_AT = [1, 2, 4, 5];
const ROTATION_ORDER = [2, 4, 5, 1];

const CORNER_COLOURS = CORNER_SLOTS.map((slots) => slots.map((slot) => Math.floor(slot / 9)));
const EDGE_COLOURS = EDGE_SLOTS.map((slots) => slots.map((slot) => Math.floor(slot / 9)));
const byColours = (table) => {
  const map = {};
  table.forEach((colours, piece) => {
    map[colours.toSorted().join("")] = piece;
  });
  return map;
};
const CORNER_BY = byColours(CORNER_COLOURS);
const EDGE_BY = byColours(EDGE_COLOURS);
const QUARTER_BY_FACE = {};
for (const row of QUARTER) QUARTER_BY_FACE[row.move] = row;

/** Facelets to cubies; the observation is the only input the solver needs. */
function decode(facelets) {
  const cp = Array.from({ length: 8 }, () => 0);
  const co = Array.from({ length: 8 }, () => 0);
  const ep = Array.from({ length: 12 }, () => 0);
  const eo = Array.from({ length: 12 }, () => 0);
  for (let slot = 0; slot < 8; slot++) {
    const colours = CORNER_SLOTS[slot].map((index) => facelets[index]);
    const piece = CORNER_BY[colours.toSorted().join("")];
    cp[slot] = piece;
    co[slot] = colours.indexOf(CORNER_COLOURS[piece][0]);
  }
  for (let slot = 0; slot < 12; slot++) {
    const colours = EDGE_SLOTS[slot].map((index) => facelets[index]);
    const piece = EDGE_BY[colours.toSorted().join("")];
    ep[slot] = piece;
    eo[slot] = colours[0] === EDGE_COLOURS[piece][0] ? 0 : 1;
  }
  return { cp, co, ep, eo };
}

function turn(cube, row) {
  const cp = Array.from({ length: 8 }, () => 0);
  const co = Array.from({ length: 8 }, () => 0);
  const ep = Array.from({ length: 12 }, () => 0);
  const eo = Array.from({ length: 12 }, () => 0);
  for (let p = 0; p < 8; p++) {
    cp[p] = cube.cp[row.cp[p]];
    co[p] = (cube.co[row.cp[p]] + row.co[p]) % 3;
  }
  for (let p = 0; p < 12; p++) {
    ep[p] = cube.ep[row.ep[p]];
    eo[p] = (cube.eo[row.ep[p]] + row.eo[p]) % 2;
  }
  return { cp, co, ep, eo };
}

function applyMove(cube, move) {
  const row = QUARTER_BY_FACE[move[0]];
  const turns = move.length === 1 ? 1 : move[1] === "2" ? 2 : 3;
  let state = cube;
  for (let step = 0; step < turns; step++) state = turn(state, row);
  return state;
}

function applySequence(cube, moves) {
  let state = cube;
  for (const move of moves) state = applyMove(state, move);
  return state;
}

function parseMoves(text) {
  return text.length === 0 ? [] : text.split(" ");
}

/** Same algorithm seen from another side of the cube; always returns a fresh array. */
function rotateAlg(alg, turns) {
  let current = alg.slice();
  for (let step = 0; step < turns; step++)
    current = current.map((move) => {
      const face = FACE_LETTERS[ROTATE_FACE[FACE_OF[move[0]]]];
      return face + move.slice(1);
    });
  return current;
}

const keyOf = (cube) =>
  `${cube.cp.join("")}|${cube.co.join("")}|${cube.ep.join(",")}|${cube.eo.join("")}`;

const crossDone = (cube) =>
  CROSS_SLOTS.every((slot) => cube.ep[slot] === slot && cube.eo[slot] === 0);
const cornerDone = (cube, slot) => cube.cp[slot] === slot && cube.co[slot] === 0;
const edgeDone = (cube, slot) => cube.ep[slot] === slot && cube.eo[slot] === 0;
const uEdgesOriented = (cube) => [0, 1, 2, 3].every((slot) => cube.eo[slot] === 0);
const uCornersOriented = (cube) => [0, 1, 2, 3].every((slot) => cube.co[slot] === 0);
const uCornersHome = (cube) => [0, 1, 2, 3].every((slot) => cube.cp[slot] === slot);
const uEdgesHome = (cube) => [0, 1, 2, 3].every((slot) => cube.ep[slot] === slot);

/** Breadth-first search over short macro sequences; macros keep the first two layers intact. */
function searchMacros(cube, goal, macros, maxDepth) {
  if (goal(cube)) return [];
  let frontier = [{ cube, path: [] }];
  const seen = { [keyOf(cube)]: true };
  for (let depth = 0; depth < maxDepth; depth++) {
    const next = [];
    for (const node of frontier)
      for (const macro of macros) {
        const after = applySequence(node.cube, macro);
        const key = keyOf(after);
        if (seen[key]) continue;
        const path = node.path.concat([macro]);
        if (goal(after)) return path.reduce((moves, item) => moves.concat(item), []);
        seen[key] = true;
        next.push({ cube: after, path });
      }
    frontier = next;
  }
  return null;
}

const withAlignments = (alg) => [alg, ["U"].concat(alg), ["U2"].concat(alg), ["U'"].concat(alg)];

/** The next algorithm to run, or null when the cube is solved. */
function planNext(cube) {
  if (!crossDone(cube)) {
    for (let k = 0; k < 4; k++) {
      const home = CROSS_SLOTS[k];
      if (cube.ep[home] === home && cube.eo[home] === 0) continue;
      const slot = cube.ep.indexOf(home);
      const entry = CROSS[k][slot * 2 + cube.eo[slot]];
      if (entry === null || entry === undefined) throw new Error("cross table miss");
      return parseMoves(entry);
    }
  }

  for (let k = 0; k < 4; k++) {
    const slot = CORNER_ORDER[k];
    if (cornerDone(cube, slot)) continue;
    const where = cube.cp.indexOf(slot);
    if (where >= 4) return rotateAlg(CORNER_POP, CORNER_ORDER.indexOf(where));
    const turns = (U_ABOVE[slot] - where + 4) % 4;
    const align = turns === 0 ? [] : turns === 1 ? ["U"] : turns === 2 ? ["U2"] : ["U'"];
    return align.concat(rotateAlg(CORNER_INSERT[cube.co[where]], k));
  }

  for (let k = 0; k < 4; k++) {
    const slot = EDGE_ORDER[k];
    if (edgeDone(cube, slot)) continue;
    const where = cube.ep.indexOf(slot);
    if (where >= 8) return rotateAlg(MIDDLE_POP, EDGE_ORDER.indexOf(where));
    for (let turns = 0; turns < 4; turns++) {
      const align = turns === 0 ? [] : turns === 1 ? ["U"] : turns === 2 ? ["U2"] : ["U'"];
      const probe = turns === 0 ? cube : applySequence(cube, align);
      const position = probe.ep.indexOf(slot);
      if (position > 3) continue;
      const sideFace = SIDE_FACE_AT[position];
      const first = EDGE_COLOURS[slot][0];
      const second = EDGE_COLOURS[slot][1];
      const sideColour = probe.eo[position] === 0 ? second : first;
      if (sideColour !== sideFace) continue;
      const other = probe.eo[position] === 0 ? first : second;
      const rotation = ROTATION_ORDER.indexOf(sideFace);
      if (RIGHT_OF[sideFace] === other) return align.concat(rotateAlg(MIDDLE_RIGHT, rotation));
      if (LEFT_OF[sideFace] === other) return align.concat(rotateAlg(MIDDLE_LEFT, rotation));
    }
    throw new Error("middle edge has no alignment");
  }

  if (!uEdgesOriented(cube)) {
    const path = searchMacros(cube, uEdgesOriented, withAlignments(LL_EDGE_ORIENT), 4);
    if (path === null) throw new Error("last-layer edges stuck");
    return path;
  }
  if (!uCornersOriented(cube)) {
    const macros = [];
    for (const alg of LL_CORNER_ORIENT) for (const item of withAlignments(alg)) macros.push(item);
    const path = searchMacros(cube, uCornersOriented, macros, 5);
    if (path === null) throw new Error("last-layer corners stuck");
    return path;
  }
  if (!uCornersHome(cube)) {
    const macros = [];
    for (const alg of LL_CORNER_PERM) for (const item of withAlignments(alg)) macros.push(item);
    const path = searchMacros(cube, uCornersHome, macros, 5);
    if (path === null) throw new Error("last-layer corner permutation stuck");
    return path;
  }
  if (!uEdgesHome(cube)) {
    const macros = [];
    for (const alg of LL_EDGE_PERM) for (const item of withAlignments(alg)) macros.push(item);
    const path = searchMacros(cube, uEdgesHome, macros, 5);
    if (path === null) throw new Error("last-layer edge permutation stuck");
    return path;
  }
  return null;
}

export default function tick({ game, Memory }) {
  if (!Array.isArray(Memory.plan) || Memory.plan.length === 0) {
    const next = planNext(decode(game.facelets));
    if (next === null) return;
    // Copy: the plan is consumed in place, and the tables are shared constants.
    Memory.plan = next.slice();
  }
  const move = Memory.plan.shift();
  game.self.turn(move);
}
