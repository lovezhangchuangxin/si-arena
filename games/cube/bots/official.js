/**
 * Official example bot for 魔方 (cube).
 *
 * A deterministic layer-by-layer solver: white cross, white corners, middle
 * edges, then four last-layer passes (edge orientation, corner orientation,
 * corner permutation, edge permutation). Every step is a table lookup or a tiny
 * breadth-first search over a handful of macros, so one call plans one whole
 * algorithm in well under a millisecond and the plan is stored in Memory.
 *
 * The solver works on cubies (piece permutation + orientation) decoded from the
 * published facelets. Facelet blocks are U 0-8, R 9-17, F 18-26, D 27-35,
 * L 36-44, B 45-53; corner slots are URF UFL ULB UBR DFR DLF DBL DRB and edge
 * slots UR UF UL UB DR DF DL DB FR FL BL BR, the usual Kociemba order.
 */

